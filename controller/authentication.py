"""Application-owned users shared by local, Entra OIDC and SAML sign-in."""
from __future__ import annotations

import copy
import os
import re
import uuid

from .auth import (AuthConflict, AuthDenied, AuthUnavailable, EntraAuth, EntraConfig,
                   ROLES, SESSION_COOKIE, STATE_COOKIE, _email, _set_cookie, _text)
from .local_auth import (BUILTIN_ADMIN_DISPLAY_NAME, LocalAuth, _password, clear_attempts, hash_password, local_fingerprint,
                         public_user, revoke_sessions, write_fence)
from .store import digest, now, parse_time, stamp


def _saml_binding(store, db):
    from .saml_auth import SAMLConfig, authority_fingerprint
    row = store._get(db, "maintenance_settings", "saml_configuration")
    if not row:
        raise AuthDenied("SAML sign-in is not configured")
    value = row.get("config", row)
    # These headers are generated by the authenticated settings writer, never
    # accepted from a browser. Bind them to the exact canonical settings.
    if (isinstance(value, dict) and value.get("enabled") is True
            and row.get("config_digest") == digest(value)
            and "epoch" in row
            and isinstance(row.get("fingerprint"), str)
            and re.fullmatch(r"[a-f0-9]{64}", row["fingerprint"])):
        try:
            realm = str(uuid.UUID(row["realm_id"]))
        except (KeyError, ValueError, TypeError, AttributeError):
            raise AuthDenied("SAML account authority is unavailable") from None
        if row["realm_id"] != realm:
            raise AuthDenied("SAML account authority is unavailable")
        if (not isinstance(row.get("epoch"), str) or not re.fullmatch(r"[a-f0-9]{64}", row["epoch"])
                or not isinstance(row.get("configuration_fingerprint"), str)
                or not re.fullmatch(r"[a-f0-9]{64}", row["configuration_fingerprint"])
                or row["fingerprint"] != digest({"configuration_fingerprint": row["configuration_fingerprint"], "epoch": row["epoch"]})):
            raise AuthDenied("SAML account authority is unavailable")
        return realm, row["fingerprint"]
    config = SAMLConfig.from_value(value)
    if not config.enabled:
        raise AuthDenied("SAML sign-in is not configured")
    return config.realm_id, authority_fingerprint(config, row)


def provider_fingerprint(store, db, provider):
    if provider == "local":
        return local_fingerprint(store, db)[1]
    if provider == "saml":
        return _saml_binding(store, db)[1]
    if provider == "entra":
        value = getattr(store, "approval_auth_fingerprint", None)
        if not value:
            config = EntraConfig.from_env()
            value = config.fingerprint if config.enabled else None
        if value:
            current = store._get(db, "maintenance_settings", "controller_provider_authority")
            if current and (current.get("fingerprint") != value or current.get("epoch", "") != os.environ.get("PRTHAK_PROVIDER_EPOCH", "")):
                raise AuthDenied("This controller has a superseded sign-in authority")
            return value
    raise AuthDenied("This sign-in provider is unavailable")


def validate_current_principal(store, db, principal, *, allow_password_change=False):
    """Revalidate current authority inside the caller's database transaction.

    This never treats a bearer role token, a public identity or a limited
    password-change session as a complete administrative session.
    """
    if not isinstance(principal, dict) or principal.get("auth_type") != "session":
        raise AuthDenied("An authenticated application session is required")
    claimed = principal.get("user")
    if not isinstance(claimed, dict) or not isinstance(claimed.get("id"), str):
        raise AuthDenied("An authenticated application user is required")
    identifier = claimed["id"]
    session_id = principal.get("_session_id")
    if not isinstance(session_id, str) or not re.fullmatch(r"[a-f0-9]{64}", session_id):
        raise AuthDenied("A current application session is required")
    user = store._get(db, "auth_users", identifier)
    session = store._get(db, "auth_sessions", session_id)
    provider = (user or {}).get("provider", "entra")
    try:
        tenant = str(uuid.UUID(user["tenant_id"]))
        person = str(uuid.UUID(user["object_id"]))
    except (KeyError, TypeError, ValueError, AttributeError):
        raise AuthDenied("The account identity is invalid") from None
    if (not user or user.get("enabled") is not True or user.get("role") not in ROLES
            or principal.get("role") != user["role"] or identifier != tenant + ":" + person
            or claimed.get("tenant_id") != tenant or claimed.get("object_id") != person
            or principal.get("auth_provider", "entra") != provider or claimed.get("provider", "entra") != provider
            or principal.get("actor") != provider + ":" + identifier
            or not session or session.get("user_id") != identifier or session.get("provider", "entra") != provider
            or parse_time(session.get("expires_at", "1970-01-01T00:00:00Z")) <= now()):
        raise AuthDenied("The application session was revoked, expired or changed")
    expected = provider_fingerprint(store, db, provider)
    if session.get("config") != expected:
        raise AuthDenied("The sign-in provider configuration changed; sign in again")
    if provider == "local":
        realm, _ = local_fingerprint(store, db)
        from .local_auth import username
        try:
            expected_person = str(uuid.uuid5(uuid.UUID(realm), username(user.get("username"))))
        except ValueError:
            raise AuthDenied("The local account identity is invalid") from None
        if (tenant != realm or not user.get("credential_version")
                or user["credential_version"] != session.get("credential_version")
                or person != expected_person):
            raise AuthDenied("The local credentials changed; sign in again")
        if not allow_password_change and (user.get("password_change_required") or session.get("password_change_required")):
            raise AuthDenied("Change the temporary local password before using the workspace")
    elif provider == "saml":
        realm, _ = _saml_binding(store, db)
        subject = user.get("subject")
        if (not isinstance(subject, str) or not subject or tenant != realm
                or person != str(uuid.uuid5(uuid.UUID(realm), subject))):
            raise AuthDenied("The SAML account identity is invalid")
    elif principal.get("password_change_required"):
        raise AuthDenied("Invalid sign-in state")
    return user


class Authentication:
    """Keep directory integration compatible while exposing real local users."""
    def __init__(self, store, entra=None, saml=None, origin=None, *, bootstrap=True):
        self.store = store
        self.entra = entra if entra is not None else EntraAuth(store)
        self.saml = saml
        self.local = LocalAuth(store, origin=origin or (self.entra.config.origin if self.entra.enabled else None), bootstrap=bootstrap)

    @property
    def config(self):
        return self.entra.config

    @property
    def provider(self):
        return self.entra.provider

    @property
    def purpose(self):
        return self.entra.purpose

    @property
    def enabled(self):
        return True

    def status(self):
        entra = self.entra.status()
        saml = self.saml.status() if self.saml is not None else {"configured": False}
        providers = [{"provider": "local", "type": "local", "name": "Local account", "enabled": True}]
        if self.entra.enabled:
            providers.append({"provider": "entra", "type": "sso", "name": "Microsoft Entra ID", "enabled": True,
                              "login_url": entra.get("login_url")})
        if self.saml is not None and self.saml.config.enabled:
            providers.append({"provider": "saml", "type": "sso", "name": saml.get("display_name", "SAML SSO"),
                              "enabled": True, "login_url": saml.get("login_url", "/api/v1/auth/saml/login")})
        return {**entra, "mode": "hybrid" if len(providers) > 1 else "local", "configured": True,
                "local_enabled": True, "providers": providers, "saml": saml,
                "entra": entra, "password_min_length": 12, "password_max_length": 256}

    def begin_login(self, headers):
        return self.entra.begin_login(headers)

    def callback(self, query, headers):
        result = self.entra.callback(query, headers)
        if result.get("principal"):
            result = {**result, "principal": self._entra_principal(result["principal"])}
        return result

    def _entra_principal(self, value):
        result = copy.deepcopy(value)
        result["auth_provider"] = "entra"
        result["user"]["provider"] = "entra"
        result["_origin"] = self.entra.config.origin
        return result

    def verify_callback_identity(self, query, headers):
        return self.entra.verify_callback_identity(query, headers)

    def local_login(self, value, headers):
        return self.local.login(value, headers)

    def authenticate(self, headers):
        value = self.local.authenticate(headers)
        if value is not None:
            return value
        if self.saml is not None:
            value = self.saml.authenticate(headers)
            if value is not None:
                return value
        value = self.entra.authenticate(headers)
        if value is not None:
            value = self._entra_principal(value)
        return value

    def require_csrf(self, headers, principal):
        if principal and principal.get("auth_type") == "session":
            self.local.require_csrf(headers, principal, origin=principal.get("_origin"))

    def logout(self, headers):
        principal = self.authenticate(headers)
        if principal:
            self.require_csrf(headers, principal)
            with self.store.lock, self.store.meta() as db:
                write_fence(db)
                db.execute("DELETE FROM auth_sessions WHERE id=?", (principal["_session_id"],))
                self.store.audit("auth.logout", principal["actor"], {"user_id": principal["user"]["id"]}, db)
        return {"cookies": [_set_cookie(SESSION_COOKIE), _set_cookie(STATE_COOKIE)]}

    def _require_super(self, principal, db):
        user = validate_current_principal(self.store, db, principal)
        if user["role"] != "super_admin":
            raise AuthDenied("Super Admin role required to manage users")
        return user

    def list_users(self, principal):
        with self.store.read_meta() as db:
            self._require_super(principal, db)
            values = self.store._all(db, "auth_users")
            return {"items": sorted((public_user(value) for value in values),
                                    key=lambda value: (value.get("display_name") or value.get("username") or value.get("email") or value["id"]).casefold())}

    def create_user(self, value, principal):
        if not isinstance(value, dict):
            raise ValueError("User must be an object")
        provider = value.get("provider", "entra")
        # Validate authority before spending work on a temporary password.
        with self.store.read_meta() as db:
            self._require_super(principal, db)
        if provider == "local":
            user = self.local.prepare_user(value)
        elif provider == "entra":
            user = self.entra._user({k: v for k, v in value.items() if k != "provider"})
            user["provider"] = "entra"
        elif provider == "saml" and self.saml is not None and self.saml.config.enabled:
            user = self.saml.user({k: v for k, v in value.items() if k != "provider"})
        else:
            raise ValueError("Choose local or a configured SSO provider")
        with self.store.lock, self.store.meta() as db:
            write_fence(db)
            self._require_super(principal, db)
            if provider == "entra":
                from .provider_lifecycle import assert_auth_current
                assert_auth_current(self.entra, db)
            if provider == "saml" and provider_fingerprint(self.store, db, "saml") != self.saml.fingerprint:
                raise AuthDenied("SAML configuration changed; review the new account again")
            if self.store._get(db, "auth_users", user["id"]):
                raise AuthConflict("This user already has a Prṛthak access record")
            if user["id"] == self.local.protected_identifier(db):
                raise AuthConflict("The built-in admin identity is reserved and cannot be recreated")
            self.store._put(db, "auth_users", user)
            if provider == "local":
                clear_attempts(self.store, db, user["username"])
            self.store.audit("access.user.created", principal["actor"], {"user_id": user["id"], "after": public_user(user)}, db)
            return public_user(user)

    def update_user(self, identifier, value, principal):
        if not isinstance(value, dict) or not value or set(value) - {"role", "enabled", "display_name", "email"}:
            raise ValueError("Only role, enabled, display_name and email can be changed")
        if "role" in value and value["role"] not in ROLES:
            raise ValueError("Choose Read Only, Admin or Super Admin")
        if "enabled" in value and not isinstance(value["enabled"], bool):
            raise ValueError("enabled must be true or false")
        edited = dict(value)
        if "display_name" in edited:
            edited["display_name"] = _text(edited["display_name"], "Display name", 200)
        if "email" in edited:
            edited["email"] = _email(edited["email"])
        with self.store.lock, self.store.meta() as db:
            write_fence(db)
            self._require_super(principal, db)
            user = self.store._get(db, "auth_users", identifier)
            if user is None:
                raise KeyError(identifier)
            if identifier == self.local.protected_identifier(db):
                if set(edited) - {"display_name", "email"}:
                    raise AuthConflict("The built-in admin account is protected; only its display name and email can be edited here")
                if identifier != principal["user"]["id"] or user.get("provider") != "local":
                    raise AuthDenied("Sign in as the built-in admin to edit its profile")
                if "display_name" in edited:
                    edited["display_name"] = edited["display_name"] or BUILTIN_ADMIN_DISPLAY_NAME
                    edited["display_name_customized"] = True
            before = public_user(user)
            after = {**user, **edited}
            changed = after["role"] != user["role"] or after["enabled"] != user["enabled"]
            if identifier == principal["user"]["id"] and changed:
                raise AuthConflict("A Super Admin cannot change their own role or disable their own account")
            if user.get("enabled") and user.get("role") == "super_admin" and (not after.get("enabled") or after.get("role") != "super_admin"):
                remaining = [other for other in self.store._all(db, "auth_users")
                             if other["id"] != identifier and other.get("enabled") is True and other.get("role") == "super_admin"
                             and not other.get("password_change_required")]
                if not remaining:
                    raise AuthConflict("Keep at least one enabled Super Admin with completed credentials")
            user.update(edited, updated_at=stamp())
            self.store._put(db, "auth_users", user)
            revoked = revoke_sessions(self.store, db, identifier) if changed else 0
            self.store.audit("access.user.updated", principal["actor"],
                             {"user_id": identifier, "before": before, "after": public_user(user), "revoked_sessions": revoked}, db)
            return {**public_user(user), "revoked_sessions": revoked}

    def revoke_sessions(self, identifier, principal):
        with self.store.lock, self.store.meta() as db:
            write_fence(db)
            self._require_super(principal, db)
            user = self.store._get(db, "auth_users", identifier)
            if user is None:
                raise KeyError(identifier)
            count = revoke_sessions(self.store, db, identifier)
            self.store.audit("access.user.sessions_revoked", principal["actor"], {"user_id": identifier, "revoked_sessions": count}, db)
            return {"user_id": identifier, "revoked_sessions": count}

    def change_password(self, value, principal, headers):
        return self.local.change_password(value, principal, headers)

    def reset_password(self, identifier, value, principal):
        if not isinstance(value, dict) or set(value) - {"password", "confirm_password"}:
            raise ValueError("Provide a temporary password and its confirmation")
        secret = _password(value.get("password"), new=True)
        if "confirm_password" in value and value["confirm_password"] != secret:
            raise ValueError("Password confirmation does not match")
        with self.store.read_meta() as db:
            self._require_super(principal, db)
            snapshot = self.store._get(db, "auth_users", identifier)
            if not snapshot:
                raise KeyError(identifier)
            if snapshot.get("provider") != "local":
                raise AuthDenied("SSO passwords are managed by the identity provider")
            if identifier == principal["user"]["id"]:
                raise AuthConflict("Use Change password for your own account")
        encoded = hash_password(secret)
        with self.store.lock, self.store.meta() as db:
            write_fence(db)
            self._require_super(principal, db)
            user = self.store._get(db, "auth_users", identifier)
            if not user or user.get("provider") != "local" or user.get("credential_version") != snapshot.get("credential_version"):
                raise AuthConflict("This account changed; review it again before resetting its password")
            user.update(password_hash=encoded, credential_version=uuid.uuid4().hex, password_change_required=True, updated_at=stamp())
            count = revoke_sessions(self.store, db, identifier)
            self.store._put(db, "auth_users", user)
            clear_attempts(self.store, db, user["username"])
            self.store.audit("access.local.password_reset", principal["actor"],
                             {"user_id": identifier, "revoked_sessions": count, "password_change_required": True}, db)
            return {**public_user(user), "revoked_sessions": count}
