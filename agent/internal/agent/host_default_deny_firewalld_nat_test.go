func TestLegacyFirewalldNATKernelContext(t *testing.T) {
	raw := legacyFirewalldNATFixture()
	if digest, err := hostDefaultDenyKernelContext(raw, "public"); err != nil || !validDigest(digest) {
		t.Fatalf("inert generated family NAT dispatch should preserve host INPUT proof: %q %v", digest, err)
	}
	foreign, err := activationForeignNftObjects(raw)
	if err != nil || strings.Contains(foreign, `"firewalld"`) {
		t.Fatalf("activation did not strip proven inert firewalld objects: %q %v", foreign, err)
	}
	for name, target := range map[string]string{
		"inbound DNAT":       `{"dnat":{"addr":"192.0.2.7"}}`,
		"outbound SNAT":      `{"snat":{"addr":"192.0.2.7"}}`,
		"opaque xt target":   `{"xt":{"type":"target","name":"REDIRECT"}}`,
		"competing terminal": `{"accept":null}`,
		"cross-direction":    `{"goto":{"target":"nat_POST_public"}}`,
		"loop":               `{"goto":{"target":"nat_PREROUTING_ZONES"}}`,
		"undeclared chain":   `{"goto":{"target":"nat_PRE_foreign"}}`,
	} {
		t.Run(name, func(t *testing.T) {
			changed := strings.Replace(raw, `{"goto":{"target":"nat_PRE_public"}}`, target, 1)
			if changed == raw || !json.Valid([]byte(changed)) {
				t.Fatal("negative fixture did not modify the expected rule")
			}
			if _, err := hostDefaultDenyKernelContext(changed, "public"); err == nil {
				t.Fatal("host INPUT proof admitted unproven family NAT behavior")
			}
			if _, err := activationForeignNftObjects(changed); err == nil {
				t.Fatal("activation treated unproven family NAT behavior as owned")
			}
		})
	}
}

func TestLegacyXTablesProbeTablesMustBeInertAndComplete(t *testing.T) {
	base := legacyFirewalldNATFixture()
	const table = `{"table":{"family":"ip","name":"raw"}}`
	const pre = `{"chain":{"family":"ip","table":"raw","name":"PREROUTING","type":"filter","hook":"prerouting","prio":-300,"policy":"accept"}}`
	const out = `{"chain":{"family":"ip","table":"raw","name":"OUTPUT","type":"filter","hook":"output","prio":-300,"policy":"accept"}}`
	const bridge = `{"table":{"family":"bridge","name":"nat"}},
{"chain":{"family":"bridge","table":"nat","name":"PREROUTING","type":"filter","hook":"prerouting","prio":-300,"policy":"accept"}},
{"chain":{"family":"bridge","table":"nat","name":"OUTPUT","type":"filter","hook":"output","prio":100,"policy":"accept"}},
{"chain":{"family":"bridge","table":"nat","name":"POSTROUTING","type":"filter","hook":"postrouting","prio":300,"policy":"accept"}}`
	with := strings.TrimSuffix(base, "]}") + "," + table + "," + pre + "," + out + "," + bridge + "]}"
	baseline, err := hostDefaultDenyKernelContext(base, "public")
	if err != nil {
		t.Fatal(err)
	}
	if digest, err := hostDefaultDenyKernelContext(with, "public"); err != nil || digest != baseline {
		t.Fatalf("exact empty probes should not affect the host INPUT proof: %q %v", digest, err)
	}
	without, err := activationForeignNftObjects(with)
	if err != nil || strings.Contains(without, `"raw"`) || strings.Contains(without, `"bridge"`) {
		t.Fatalf("activation did not omit exact empty probes: %q %v", without, err)
	}
	if _, err := activationInactiveKernel(`{"nftables":[`+table+","+pre+","+out+"]}", false, nil); err != nil {
		t.Fatalf("exact inactive xtables probes should be inert: %v", err)
	}
	for name, changed := range map[string]string{
		"active rule": strings.Replace(with, pre, pre+`,{"rule":{"family":"ip","table":"raw","chain":"PREROUTING","expr":[{"drop":null}]}}`, 1),
		"priority":    strings.Replace(with, pre, strings.Replace(pre, "-300", "-299", 1), 1),
		"missing":     strings.Replace(with, ","+out, "", 1),
	} {
		t.Run(name, func(t *testing.T) {
			if changed == with || !json.Valid([]byte(changed)) {
				t.Fatal("probe mutation did not match fixture")
			}
			if _, err := hostDefaultDenyKernelContext(changed, "public"); err == nil {
				t.Fatal("unproven probe table was accepted")
			}
			if _, err := activationForeignNftObjects(changed); err == nil {
				t.Fatal("activation omitted an unproven probe table")
			}
		})
	}
}

// These families, hooks and dispatch names are generated by firewalld
// 0.9.11's nftables backend in Enterprise Linux 8.
func legacyFirewalldNATFixture() string {
	raw := strings.TrimSuffix(hostDenyKernelFixture(), "]}")
	for _, family := range []string{"ip", "ip6"} {
		raw += fmt.Sprintf(`,{"table":{"family":%q,"name":"firewalld"}}`, family)
		for _, hook := range []struct {
			base, hook, zone, iface string
			priority                int
		}{
			{"nat_PREROUTING", "prerouting", "nat_PRE_public", "iifname", -90},
			{"nat_POSTROUTING", "postrouting", "nat_POST_public", "oifname", 110},
		} {
			raw += fmt.Sprintf(`,{"chain":{"family":%q,"table":"firewalld","name":%q,"type":"nat","hook":%q,"prio":%d,"policy":"accept"}}`, family, hook.base, hook.hook, hook.priority)
			for _, suffix := range []string{"_POLICIES_pre", "_ZONES", "_POLICIES_post"} {
				raw += fmt.Sprintf(`,{"chain":{"family":%q,"table":"firewalld","name":%q}}`, family, hook.base+suffix)
			}
			raw += fmt.Sprintf(`,{"chain":{"family":%q,"table":"firewalld","name":%q}}`, family, hook.zone)
			for _, suffix := range []string{"_POLICIES_pre", "_ZONES", "_POLICIES_post"} {
				raw += fmt.Sprintf(`,{"rule":{"family":%q,"table":"firewalld","chain":%q,"expr":[{"jump":{"target":%q}}]}}`, family, hook.base, hook.base+suffix)
			}
			raw += fmt.Sprintf(`,{"rule":{"family":%q,"table":"firewalld","chain":%q,"expr":[{"match":{"op":"==","left":{"meta":{"key":%q}},"right":"eth0"}},{"goto":{"target":%q}}]}}`, family, hook.base+"_ZONES", hook.iface, hook.zone)
		}
	}
	return raw + "]}"
}
